# Helper function to get all WAV files in a directory and its subdirectories
def get_all_wav_files(base_path):
    wav_files = []
    for root, _, files in os.walk(base_path):
        for file in files:
            if file.endswith(".wav"):
                wav_files.append(os.path.join(root, file))
    return wav_files

