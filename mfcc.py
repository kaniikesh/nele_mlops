import librosa
import numpy as np
import os
import random
import zipfile
import matplotlib.pyplot as plt

zip_files = ["archive (1).zip", "archive (2).zip"]

for z in zip_files:
    with zipfile.ZipFile(z, 'r') as zip_ref:
        zip_ref.extractall("/content/data")

